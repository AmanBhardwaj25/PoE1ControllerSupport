using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEngine;

namespace PoEController.Input
{
    /// <summary>One spell / ability in haptics/spell_index.json.</summary>
    [Serializable]
    public sealed class HapticIndexEntry
    {
        /// <summary>The abilities string-table ids of its display name (so it works in every game language).</summary>
        public int[] ids;
        public string name;
        /// <summary>Pattern file name without .json (haptics/spells or haptics/custom).</summary>
        public string file;
        /// <summary>Bucket file name without .json (haptics/buckets); "" = pick by attack kind.</summary>
        public string bucket;
        public bool popular;
        /// <summary>Light colours read from the spell's icon art (empty = use the bucket's).</summary>
        public Color[] colors = new Color[0];
    }

    [Serializable]
    public sealed class HapticIndexFile
    {
        public HapticIndexEntry[] entries;
    }

    /// <summary>
    /// Which spell a hit came from: the shipped haptics/spell_index.json maps each ability's display-name string id
    /// to its pattern file name and bucket (variants such as scrolls, necklaces, traps and enemy versions share the
    /// spell's name, so they share its file). Writes haptics/spell_ids.txt for people making pattern files.
    /// </summary>
    public static class HapticIndex
    {
        private static readonly Dictionary<int, HapticIndexEntry> s_ById = new Dictionary<int, HapticIndexEntry>();

        public static int Count => s_ById.Count;

        public static void Load(string hapticsDir)
        {
            s_ById.Clear();
            string path = Path.Combine(hapticsDir, "spell_index.json");
            if (!File.Exists(path))
            {
                Plugin.Log.LogWarning("Haptics: spell_index.json missing; spells use the bucket picked by their attack kind");
                return;
            }
            var file = new HapticIndexFile();
            try
            {
                file.entries = Parse(File.ReadAllText(path));
            }
            catch (Exception e)
            {
                Plugin.Log.LogWarning($"Haptics: spell_index.json can't be read ({e.Message}); spells use the bucket picked by their attack kind");
                return;
            }
            var lines = new StringBuilder();
            lines.AppendLine("# Every spell / ability the mod knows: in-game name | pattern file (haptics/spells or haptics/custom) | bucket (haptics/buckets) | light colours");
            lines.AppendLine("# Put your own <file>.json into haptics/custom to change how a spell feels. Generated by PoE Controller.");
            foreach (HapticIndexEntry e in file.entries ?? new HapticIndexEntry[0])
            {
                if (e == null || e.ids == null)
                {
                    continue;
                }
                foreach (int id in e.ids)
                {
                    s_ById[id] = e;
                }
                string colours = e.colors.Length > 0 ? string.Join(" ", Array.ConvertAll(e.colors, c => "#" + ColorUtility.ToHtmlStringRGB(c).ToLowerInvariant())) : "-";
                lines.AppendLine($"{e.name} | {e.file}.json | {(string.IsNullOrEmpty(e.bucket) ? "-" : e.bucket)} | {colours}");
            }
            try
            {
                File.WriteAllText(Path.Combine(hapticsDir, "spell_ids.txt"), lines.ToString());
            }
            catch (Exception)
            {
                // Read-only install: the list is only a convenience.
            }
            Plugin.Log.LogInfo($"Haptics: {file.entries?.Length ?? 0} spells and abilities indexed");
        }

        private static HapticIndexEntry[] Parse(string json)
        {
            var list = new List<HapticIndexEntry>();
            var root = MiniJson.Parse(json) as Dictionary<string, object>;
            foreach (object o in MiniJson.List(root, "entries") ?? new List<object>())
            {
                if (!(o is Dictionary<string, object> d))
                {
                    continue;
                }
                var ids = new List<int>();
                foreach (object id in MiniJson.List(d, "ids") ?? new List<object>())
                {
                    if (id is double n)
                    {
                        ids.Add((int)n);
                    }
                }
                list.Add(new HapticIndexEntry
                {
                    ids = ids.ToArray(),
                    name = MiniJson.Text(d, "name", ""),
                    file = MiniJson.Text(d, "file", ""),
                    bucket = MiniJson.Text(d, "bucket", ""),
                    popular = d.TryGetValue("popular", out object pop) && pop is bool b && b,
                    colors = HapticPattern.Colors(MiniJson.List(d, "colors")),
                });
            }
            return list.ToArray();
        }

        /// <summary>The entry for an ability, by its display-name string id, or null.</summary>
        public static HapticIndexEntry For(GenericAbility ability)
        {
            if (ability == null || ability.DisplayName == null)
            {
                return null;
            }
            return s_ById.TryGetValue(ability.DisplayName.StringID, out HapticIndexEntry e) ? e : null;
        }
    }
}
